#!/usr/bin/env sh
set -eu

command -v kubectl >/dev/null || {
  echo "kubectl is required" >&2
  exit 1
}

random_token() {
  if command -v openssl >/dev/null; then
    openssl rand -hex 32
  else
    head -c 32 /dev/urandom | base64 | tr -d '\n'
  fi
}

secret_value() {
  namespace="$1"
  secret="$2"
  key="$3"
  encoded="$(kubectl -n "$namespace" get secret "$secret" -o "jsonpath={.data.$key}" 2>/dev/null || true)"
  [ -n "$encoded" ] || return 0
  printf '%s' "$encoded" | base64 -D 2>/dev/null || printf '%s' "$encoded" | base64 -d
}

# Preserve an existing database password. PostgreSQL stores its original
# password in its data volume, so replacing it during a redeploy would make the
# controller unable to connect.
postgres_password="$(secret_value benchmark-data benchmark-postgres-auth POSTGRES_PASSWORD)"
[ -n "$postgres_password" ] || postgres_password="$(random_token)"

agent_token="$(secret_value benchmark-system modelgauge-agent-auth token)"
[ -n "$agent_token" ] || agent_token="$(random_token)"

admin_token="$(secret_value benchmark-system modelgauge-admin-auth token)"
[ -n "$admin_token" ] || admin_token="$(random_token)"

kubectl apply -f namespaces.yaml

kubectl -n benchmark-data create secret generic benchmark-postgres-auth \
  --from-literal=POSTGRES_DB=benchmark \
  --from-literal=POSTGRES_USER=benchmark_app \
  --from-literal=POSTGRES_PASSWORD="$postgres_password" \
  --dry-run=client -o yaml | kubectl apply -f -

kubectl -n benchmark-system create secret generic benchmark-controller-db \
  --from-literal=DATABASE_HOST=benchmark-postgres.benchmark-data.svc.cluster.local \
  --from-literal=DATABASE_PORT=5432 \
  --from-literal=DATABASE_NAME=benchmark \
  --from-literal=DATABASE_USER=benchmark_app \
  --from-literal=DATABASE_PASSWORD="$postgres_password" \
  --dry-run=client -o yaml | kubectl apply -f -

kubectl -n benchmark-system create secret generic modelgauge-agent-auth \
  --from-literal=token="$agent_token" \
  --dry-run=client -o yaml | kubectl apply -f -

kubectl -n benchmark-system create secret generic modelgauge-admin-auth \
  --from-literal=token="$admin_token" \
  --dry-run=client -o yaml | kubectl apply -f -

umask 077
control_config="${MODELGAUGE_CONTROL_CONFIG:-$HOME/.config/modelgauge/control.env}"
mkdir -p "$(dirname "$control_config")"
cat > "$control_config" <<EOF
# Generated by create-secrets.sh. Keep this file private.
MODELGAUGE_AGENT_TOKEN=$agent_token
MODELGAUGE_ADMIN_TOKEN=$admin_token
EOF

echo "Created or updated Kubernetes secrets."
echo "Credentials saved to $control_config"
